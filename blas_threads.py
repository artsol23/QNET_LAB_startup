"""Ограничение числа потоков BLAS в NumPy и SciPy.

NumPy и SciPy в поставке несут каждый свою OpenBLAS, и это отдельные
потоки: :func:`device_runtime.apply_cpu_threads` на них не действует.
Пул потоков создаётся при загрузке библиотеки, то есть при первом
``import numpy``, и число потоков читается только в этот момент.
Поэтому :func:`limit_blas_threads` вызывается в самом начале точки
входа, до первого импорта NumPy (main.py, examples/train_q13.py).

Зачем ограничивать. По умолчанию OpenBLAS берёт все логические CPU: на
16-ядерном процессоре с SMT это 32 потока, вдвое больше физических
ядер, и такой пул мешает сам себе. Замер на Q13
(examples/train_q13.py, 40 эпох, 48 057 трасс): 1 поток — 8.6 с,
2 — 8.5 с, 4 — 8.7 с, 8 — 8.6 с, 16 — 9.9 с, 32 (умолчание) — 17.7 с;
точность на отложенной части одинакова (0.7708). Ограничение вредит
только крупным матрицам — поиск утечки (eigh 2000x2000) идёт 0.24 с
на восьми потоках и 0.54 с на одном.
"""

from __future__ import annotations

import os

#: Потолок числа потоков BLAS: на нём обучение так же быстро, как на
#: одном потоке, а eigh в поиске утечки заметно быстрее.
MAX_BLAS_THREADS = 8

#: Переменная, которую читает OpenBLAS при загрузке.
BLAS_THREADS_VAR = "OPENBLAS_NUM_THREADS"


def blas_threads() -> int:
    """Сколько потоков BLAS выставить: до восьми, но не больше CPU."""
    return max(1, min(MAX_BLAS_THREADS, os.cpu_count() or 1))


def limit_blas_threads() -> None:
    """Ограничить BLAS до :func:`blas_threads`.

    Вызывать до первого ``import numpy``: позже OpenBLAS переменную не
    читает. Значение, выставленное пользователем в окружении, не
    перебивается.
    """
    os.environ.setdefault(BLAS_THREADS_VAR, str(blas_threads()))
